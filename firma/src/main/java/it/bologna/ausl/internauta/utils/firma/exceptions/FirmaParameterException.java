public class FirmaParameterException extends Exception {

    public FirmaParameterException(String message) {
        super(message);
    }

    public FirmaParameterException(Throwable cause) {
        super(cause);
    }

    public FirmaParameterException(String message, Throwable cause) {
        super(message, cause);
    }
    
}
